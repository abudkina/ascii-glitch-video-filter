/** Типы режимов фильтра */
export type РежимФильтра = 'ascii' | 'glitch';

/** Формат записи */
export type ФорматЗаписи = 'webm' | 'gif';

/** Параметры обработки кадра */
export interface ПараметрыФильтра {
  режим: РежимФильтра;
  сила: number; // 0–100
  ширина: number;
  высота: number;
}

/** Результат обработки кадра */
export interface РезультатКадра {
  данные: ImageData;
  ширина: number;
  высота: number;
}

/** Сообщение воркеру */
export interface СообщениеВоркеру {
  тип: 'обработать';
  id: number;
  буфер: ArrayBuffer;
  ширина: number;
  высота: number;
  режим: РежимФильтра;
  сила: number;
}

/** Ответ воркера */
export interface ОтветВоркера {
  тип: 'готово' | 'ошибка';
  id: number;
  буфер?: ArrayBuffer;
  ширина?: number;
  высота?: number;
  сообщение?: string;
}

/** Настройки, сохраняемые в LocalStorage */
export interface НастройкиПриложения {
  режим: РежимФильтра;
  сила: number;
  формат: ФорматЗаписи;
}

/** Состояние записи */
export type СостояниеЗаписи = 'ожидание' | 'запись' | 'готово' | 'ошибка';
