import type { НастройкиПриложения, РежимФильтра, ФорматЗаписи } from '../types';
import { ограничить } from './errors';
import { логгер } from './logger';

const КЛЮЧ = 'ascii-glitch-настройки';

const ПО_УМОЛЧАНИЮ: НастройкиПриложения = {
  режим: 'ascii',
  сила: 50,
  формат: 'webm',
  фотобудка: false,
};

function этоРежим(значение: unknown): значение is РежимФильтра {
  return значение === 'ascii' || значение === 'glitch';
}

function этоФормат(значение: unknown): значение is ФорматЗаписи {
  return значение === 'webm' || значение === 'gif';
}

/** Загрузка настроек из LocalStorage */
export function загрузитьНастройки(): НастройкиПриложения {
  try {
    const сырой = localStorage.getItem(КЛЮЧ);
    if (!сырой) return { ...ПО_УМОЛЧАНИЮ };

    const разобранный = JSON.parse(сырой) as Partial<НастройкиПриложения>;
    return {
      режим: этоРежим(разобранный.режим) ? разобранный.режим : ПО_УМОЛЧАНИЮ.режим,
      сила: ограничить(Number(разобранный.сила ?? ПО_УМОЛЧАНИЮ.сила), 0, 100),
      формат: этоФормат(разобранный.формат) ? разобранный.формат : ПО_УМОЛЧАНИЮ.формат,
      фотобудка: Boolean(разобранный.фотобудка),
    };
  } catch (ошибка) {
    логгер.предупреждение('Не удалось прочитать настройки', ошибка);
    return { ...ПО_УМОЛЧАНИЮ };
  }
}

/** Сохранение настроек в LocalStorage */
export function сохранитьНастройки(настройки: НастройкиПриложения): void {
  try {
    const безопасные: НастройкиПриложения = {
      режим: этоРежим(настройки.режим) ? настройки.режим : ПО_УМОЛЧАНИЮ.режим,
      сила: ограничить(настройки.сила, 0, 100),
      формат: этоФормат(настройки.формат) ? настройки.формат : ПО_УМОЛЧАНИЮ.формат,
      фотобудка: Boolean(настройки.фотобудка),
    };
    localStorage.setItem(КЛЮЧ, JSON.stringify(безопасные));
  } catch (ошибка) {
    логгер.предупреждение('Не удалось сохранить настройки', ошибка);
  }
}

export { ПО_УМОЛЧАНИЮ };
