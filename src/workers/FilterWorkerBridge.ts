import type { РежимФильтра, ОтветВоркера, СообщениеВоркеру } from '../types';
import { применитьФильтр } from '../filters';
import { логгер } from '../utils/logger';

type Колбэк = (данные: ImageData) => void;
type КолбэкОшибки = (сообщение: string) => void;

/**
 * Мост к Web Worker с запасным вариантом на главном потоке.
 */
export class МостФильтрВоркера {
  private воркер: Worker | null = null;
  private счётчик = 0;
  private ожидания = new Map<
    number,
    { успех: Колбэк; ошибка: КолбэкОшибки }
  >();
  private занят = false;
  private пропущенный: {
    данные: ImageData;
    режим: РежимФильтра;
    сила: number;
    успех: Колбэк;
    ошибка: КолбэкОшибки;
  } | null = null;

  constructor() {
    try {
      this.воркер = new Worker(new URL('./filter.worker.ts', import.meta.url), {
        type: 'module',
      });
      this.воркер.onmessage = (событие: MessageEvent<ОтветВоркера>) => {
        this.обработатьОтвет(событие.data);
      };
      this.воркер.onerror = (событие) => {
        логгер.ошибка('Сбой воркера фильтра', событие.message);
        this.воркер = null;
      };
    } catch (ошибка) {
      логгер.предупреждение('Воркер недоступен, обработка на главном потоке', ошибка);
      this.воркер = null;
    }
  }

  /** Обработать кадр (с дросселированием — берём только актуальный) */
  обработать(
    данные: ImageData,
    режим: РежимФильтра,
    сила: number,
    успех: Колбэк,
    ошибка: КолбэкОшибки,
  ): void {
    if (this.занят) {
      this.пропущенный = { данные, режим, сила, успех, ошибка };
      return;
    }

    this.занят = true;
    this.запустить(данные, режим, сила, успех, ошибка);
  }

  private запустить(
    данные: ImageData,
    режим: РежимФильтра,
    сила: number,
    успех: Колбэк,
    ошибка: КолбэкОшибки,
  ): void {
    if (!this.воркер) {
      try {
        const результат = применитьФильтр(данные, режим, сила);
        успех(результат);
      } catch (e) {
        ошибка(e instanceof Error ? e.message : 'Ошибка фильтра');
      }
      this.занят = false;
      this.обработатьПропущенный();
      return;
    }

    const id = ++this.счётчик;
    this.ожидания.set(id, { успех, ошибка });

    const копия = данные.data.buffer.slice(0);
    const сообщение: СообщениеВоркеру = {
      тип: 'обработать',
      id,
      буфер: копия,
      ширина: данные.width,
      высота: данные.height,
      режим,
      сила,
    };

    this.воркер.postMessage(сообщение, [копия]);
  }

  private обработатьОтвет(ответ: ОтветВоркера): void {
    const ожидание = this.ожидания.get(ответ.id);
    this.ожидания.delete(ответ.id);
    this.занят = false;

    if (!ожидание) {
      this.обработатьПропущенный();
      return;
    }

    if (ответ.тип === 'готово' && ответ.буфер && ответ.ширина && ответ.высота) {
      const пиксели = new Uint8ClampedArray(ответ.буфер);
      ожидание.успех(new ImageData(пиксели, ответ.ширина, ответ.высота));
    } else {
      ожидание.ошибка(ответ.сообщение ?? 'Неизвестная ошибка воркера');
    }

    this.обработатьПропущенный();
  }

  private обработатьПропущенный(): void {
    if (!this.пропущенный) return;
    const след = this.пропущенный;
    this.пропущенный = null;
    this.занят = true;
    this.запустить(след.данные, след.режим, след.сила, след.успех, след.ошибка);
  }

  уничтожить(): void {
    this.воркер?.terminate();
    this.воркер = null;
    this.ожидания.clear();
    this.пропущенный = null;
  }
}
