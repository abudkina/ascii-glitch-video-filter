import { describe, it, expect } from 'vitest';
import {
  вычислитьКвадратныйКроп,
  размерСтикера,
  обрезатьВКвадрат,
} from '../../src/utils/square';

function прямоугольник(w: number, h: number, r = 10, g = 20, b = 30): ImageData {
  const data = new Uint8ClampedArray(w * h * 4);
  for (let i = 0; i < data.length; i += 4) {
    data[i] = r;
    data[i + 1] = g;
    data[i + 2] = b;
    data[i + 3] = 255;
  }
  return new ImageData(data, w, h);
}

describe('вычислитьКвадратныйКроп', () => {
  it('для квадрата — без смещения', () => {
    expect(вычислитьКвадратныйКроп(100, 100)).toEqual({ x: 0, y: 0, размер: 100 });
  });

  it('для альбома — кроп по центру горизонтали', () => {
    expect(вычислитьКвадратныйКроп(200, 100)).toEqual({ x: 50, y: 0, размер: 100 });
  });

  it('для портрета — кроп по центру вертикали', () => {
    expect(вычислитьКвадратныйКроп(80, 200)).toEqual({ x: 0, y: 60, размер: 80 });
  });

  it('нулевые размеры безопасны', () => {
    expect(вычислитьКвадратныйКроп(0, 10).размер).toBe(0);
  });
});

describe('размерСтикера', () => {
  it('не превышает максимум', () => {
    expect(размерСтикера(800, 480)).toBe(480);
  });

  it('не увеличивает мелкий кадр', () => {
    expect(размерСтикера(200, 480)).toBe(200);
  });
});

describe('обрезатьВКвадрат', () => {
  it('возвращает квадрат из прямоугольника', () => {
    const вход = прямоугольник(40, 20);
    const выход = обрезатьВКвадрат(вход);
    expect(выход.width).toBe(20);
    expect(выход.height).toBe(20);
  });

  it('масштабирует до стороны стикера', () => {
    const вход = прямоугольник(60, 40, 255, 0, 0);
    const выход = обрезатьВКвадрат(вход, 10);
    expect(выход.width).toBe(10);
    expect(выход.height).toBe(10);
    expect(выход.data[0]).toBe(255);
  });

  it('сохраняет 1:1 для уже квадратного кадра', () => {
    const вход = прямоугольник(32, 32);
    const выход = обрезатьВКвадрат(вход);
    expect(выход.width).toBe(32);
    expect(выход.height).toBe(32);
  });
});
