import { describe, it, expect, beforeEach } from 'vitest';
import { загрузитьНастройки, сохранитьНастройки, ПО_УМОЛЧАНИЮ } from '../../src/utils/storage';

describe('хранилище настроек', () => {
  beforeEach(() => {
    localStorage.clear();
  });

  it('возвращает значения по умолчанию', () => {
    expect(загрузитьНастройки()).toEqual(ПО_УМОЛЧАНИЮ);
  });

  it('сохраняет и загружает настройки', () => {
    сохранитьНастройки({ режим: 'glitch', сила: 77, формат: 'gif', фотобудка: true });
    expect(загрузитьНастройки()).toEqual({
      режим: 'glitch',
      сила: 77,
      формат: 'gif',
      фотобудка: true,
    });
  });

  it('отбрасывает некорректный режим', () => {
    localStorage.setItem(
      'ascii-glitch-настройки',
      JSON.stringify({ режим: 'неизвестно', сила: 10, формат: 'webm' }),
    );
    expect(загрузитьНастройки().режим).toBe(ПО_УМОЛЧАНИЮ.режим);
  });

  it('ограничивает силу 0–100', () => {
    сохранитьНастройки({ режим: 'ascii', сила: 250, формат: 'webm', фотобудка: false });
    expect(загрузитьНастройки().сила).toBe(100);

    сохранитьНастройки({ режим: 'ascii', сила: -5, формат: 'webm', фотобудка: false });
    expect(загрузитьНастройки().сила).toBe(0);
  });

  it('переживает битый JSON', () => {
    localStorage.setItem('ascii-glitch-настройки', '{не json');
    expect(загрузитьНастройки()).toEqual(ПО_УМОЛЧАНИЮ);
  });
});
